   continuam válidas.

   COERÊNCIA DOS DADOS (todas as regras de negócio do minimundo são respeitadas)
     - Cada paciente tem 1 UBS de referência e exatamente 1 prontuário (regra 1).
     - Nenhuma dose é repetida por paciente (regra 2, garantida pela PK).
     - O lote de cada aplicação é da mesma vacina da dose (regra 3, FK composta).
     - Nenhuma aplicação usa lote já vencido na data da aplicação (regra 4);
       os lotes são escolhidos pelo critério PVPS/FEFO (primeiro a vencer).
     - APLICADA tem data, lote, profissional e UBS; PENDENTE não tem (regra 5).
     - O profissional que aplicou é lotado na UBS onde a dose foi aplicada, e o
       lote aplicado consta no Estoque_UBS dessa UBS (regras 6 e 7).
     - Estoque: quantidade_total do lote = doses distribuídas às UBS (aplicadas +
