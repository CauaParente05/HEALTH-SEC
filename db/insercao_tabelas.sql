-- 13.1 ON UPDATE CASCADE (Paciente.cnes, Profissional.cnes, Estoque_UBS.cnes, telefones)
--      Trocamos o CNES da UBS de demonstração; os filhos acompanham automaticamente.
START TRANSACTION;
SELECT 'ANTES' AS momento,
       (SELECT COUNT(*) FROM Paciente     WHERE cnes = '2405068') AS pacientes,
       (SELECT COUNT(*) FROM Profissional WHERE cnes = '2405068') AS profissionais,
       (SELECT COUNT(*) FROM Estoque_UBS  WHERE cnes = '2405068') AS estoque,
       (SELECT COUNT(*) FROM UBS_Telefone WHERE cnes = '2405068') AS telefones;
UPDATE UBS SET cnes = '2499999' WHERE cnes = '2405068';
SELECT 'DEPOIS' AS momento,
       (SELECT COUNT(*) FROM Paciente     WHERE cnes = '2499999') AS pacientes,
       (SELECT COUNT(*) FROM Profissional WHERE cnes = '2499999') AS profissionais,
       (SELECT COUNT(*) FROM Estoque_UBS  WHERE cnes = '2499999') AS estoque,
       (SELECT COUNT(*) FROM UBS_Telefone WHERE cnes = '2499999') AS telefones;
ROLLBACK;

