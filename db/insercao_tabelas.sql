--      Excluímos o responsável: os dependentes continuam cadastrados, com cns_responsavel = NULL.
START TRANSACTION;
SELECT 'ANTES' AS momento,
       (SELECT COUNT(*) FROM Paciente WHERE cns_responsavel = '125848948297667') AS dependentes_com_responsavel,
       (SELECT COUNT(*) FROM Prontuario WHERE cns = '125848948297667') AS prontuarios,
       (SELECT COUNT(*) FROM Paciente_Telefone WHERE cns = '125848948297667') AS telefones,
       (SELECT COUNT(*) FROM Registro_Dose WHERE cns = '125848948297667') AS doses;
DELETE FROM Paciente WHERE cns = '125848948297667';
SELECT 'DEPOIS' AS momento,
       (SELECT COUNT(*) FROM Paciente WHERE cns IN ('701229498887468', '243168829776204') AND cns_responsavel IS NULL) AS dependentes_sem_responsavel,
       (SELECT COUNT(*) FROM Prontuario WHERE cns = '125848948297667') AS prontuarios,
       (SELECT COUNT(*) FROM Paciente_Telefone WHERE cns = '125848948297667') AS telefones,
       (SELECT COUNT(*) FROM Registro_Dose WHERE cns = '125848948297667') AS doses;
ROLLBACK;

