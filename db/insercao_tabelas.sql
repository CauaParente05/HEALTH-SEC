DELETE FROM Profissional WHERE id_profissional = 10;
SELECT 'DEPOIS' AS momento, COUNT(*) AS profissionais_com_supervisor_nulo FROM Profissional
 WHERE id_supervisor IS NULL AND id_profissional > 10;
ROLLBACK;

